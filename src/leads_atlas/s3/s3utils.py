from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from urllib.parse import urlparse

from botocore.exceptions import ClientError
from tqdm.auto import tqdm


def ensure_gitignore(cache_dir: Path) -> None:
    """Ensures `cache_dir` exists and contains a .gitignore that ignores contents."""
    cache_dir.mkdir(parents=True, exist_ok=True)
    gi = cache_dir / ".gitignore"
    if not gi.exists():
        gi.write_text("# Auto-generated by S3Directory/S3File\n*\n!.gitignore\n")


@dataclass(frozen=True)
class S3Location:
    """Parsed representation of an S3 URI."""

    bucket: str
    key: str  # may be "" for "s3://bucket"


def parse_s3_uri(uri: str) -> S3Location:
    """Parse an S3 URI like 's3://bucket/key' into bucket and key."""
    u = urlparse(uri)
    if u.scheme != "s3":
        raise ValueError(f"Not an s3 uri: {uri}")
    if not u.netloc:
        raise ValueError(f"Missing bucket in uri: {uri}")
    return S3Location(bucket=u.netloc, key=u.path.lstrip("/"))


def head_size_bytes(s3, *, bucket: str, key: str) -> int | None:
    """Return object size in bytes from HEAD, or None if unavailable."""
    try:
        r = s3.head_object(Bucket=bucket, Key=key)
        return int(r.get("ContentLength")) if "ContentLength" in r else None
    except ClientError:
        return None


def format_s3_location(bucket: str, key: str) -> str:
    """Human-friendly string for a key: '<name> (s3://bucket/parent)'."""
    name = Path(key).name
    parent = str(Path(key).parent)
    loc = f"s3://{bucket}" if parent == "." else f"s3://{bucket}/{parent}"
    return f"{name} ({loc})"


class TqdmBytesCallback:
    """boto3 download_file Callback adapter for tqdm."""

    def __init__(self, pbar: tqdm):
        self._pbar = pbar

    def __call__(self, bytes_amount: int) -> None:
        self._pbar.update(bytes_amount)


def get_s3_tqdm_callback(s3, bucket, key, total_bytes):
    total = (
        total_bytes
        if total_bytes is not None
        else head_size_bytes(s3, bucket=bucket, key=key)
    )
    pbar = tqdm(
        total=total,
        desc=f"  {format_s3_location(bucket, key)}",
        unit="B",
        unit_scale=True,
        unit_divisor=1024,
        leave=False,
    )
    callback = TqdmBytesCallback(pbar)
    return pbar, callback


def download_s3_object(
    *,
    s3,
    bucket: str,
    key: str,
    dst: Path,
    show_progress: bool = True,
    total_bytes: int | None = None,
) -> Path:
    """Download a single S3 object to a local path, optionally with a tqdm bar."""
    dst.parent.mkdir(parents=True, exist_ok=True)

    pbar = None
    callback = None
    if show_progress:
        pbar, callback = get_s3_tqdm_callback(s3, bucket, key, total_bytes)

    try:
        s3.download_file(bucket, key, str(dst), Callback=callback)
    finally:
        if pbar is not None:
            pbar.close()

    return dst


def fetch_or_download(
    *,
    s3,
    bucket: str,
    key: str,
    dst: Path,
    use_cache: bool = True,
    show_progress: bool = True,
    total_bytes: int | None = None,
) -> Path:
    """Return a local copy of an S3 object, downloading it only if needed.

    If ``use_cache`` is True and ``dst`` already exists, the existing file is
    returned immediately. Otherwise, the object is downloaded from S3.
    """
    if use_cache and dst.is_file():
        return dst
    return download_s3_object(
        s3=s3,
        bucket=bucket,
        key=key,
        dst=dst,
        show_progress=show_progress,
        total_bytes=total_bytes,
    )


def as_patterns(pats: str | list[str] | None) -> list[str]:
    """Normalize a glob pattern input into a list."""
    if pats is None:
        return []
    return [pats] if isinstance(pats, str) else list(pats)


def matches_globs(rel_key: str, *, allowlist: list[str], blocklist: list[str]) -> bool:
    """Return True if rel_key passes allowlist/blocklist globs (supports '**')."""
    p = PurePosixPath(rel_key)
    if allowlist and not any(p.match(pat) for pat in allowlist):
        return False
    if blocklist and any(p.match(pat) for pat in blocklist):
        return False
    return True


def list_s3_objects(
    *,
    s3,
    bucket: str,
    prefix: str,
    allowlist: list[str] | None = None,
    blocklist: list[str] | None = None,
) -> list[dict]:
    """List objects under a prefix, filtered by allowlist/blocklist."""
    allowlist = allowlist or []
    blocklist = blocklist or []

    list_prefix = "" if prefix == "" else (prefix.rstrip("/") + "/")

    paginator = s3.get_paginator("list_objects_v2")
    objs: list[dict] = []

    for page in paginator.paginate(Bucket=bucket, Prefix=list_prefix):
        for obj in page.get("Contents", []):
            key = obj["Key"]
            if key.endswith("/"):
                continue
            rel = key[len(list_prefix) :] if list_prefix else key
            if matches_globs(rel, allowlist=allowlist, blocklist=blocklist):
                objs.append({"Key": key, "Size": int(obj.get("Size", 0))})

    return objs


def s3_prefix_to_local_dir(*, cache_dir: Path, bucket: str, prefix: str) -> Path:
    """Map bucket/prefix to a local directory under cache_dir."""
    prefix = prefix.rstrip("/")
    return cache_dir / bucket / Path(prefix) if prefix else (cache_dir / bucket)
